#!/usr/bin/env bash
# Assembles the self-contained production bundle from `.next/standalone`.
# Run after `npm run build`. Usage: scripts/bundle-standalone.sh [output-dir]  (default: deploy)
set -euo pipefail

out="${1:-deploy}"
rm -rf "$out"
cp -R .next/standalone "$out"

# Static assets are not part of the standalone trace.
mkdir -p "$out/.next"
cp -R .next/static "$out/.next/static"
if [ -d public ]; then cp -R public "$out/public"; fi

# Migrations, runnable on the server without drizzle-kit: `node scripts/migrate.mjs`.
mkdir -p "$out/scripts"
cp scripts/migrate.mjs "$out/scripts/migrate.mjs"
rm -rf "$out/drizzle"
cp -R drizzle "$out/drizzle"

# Image optimization is disabled (next.config.ts): sharp's native binaries are dead weight.
rm -rf "$out/node_modules/sharp" "$out/node_modules/@img"

# Never ship env files: production variables live in the hosting panel (or in a .env
# created directly on the server, which this .gitignore keeps out of the deploy branch).
rm -f "$out"/.env*
printf '.env*\n' > "$out/.gitignore"

# Minimal manifest without dependencies: an `npm install` on the host is a no-op.
node -e '
const pkg = require("./package.json");
const manifest = {
  name: pkg.name,
  version: pkg.version,
  private: true,
  description: "Production bundle generated by CI. Start with: node server.js",
  engines: pkg.engines,
  scripts: { start: "node server.js", migrate: "node scripts/migrate.mjs" },
};
process.stdout.write(JSON.stringify(manifest, null, 2) + "\n");
' > "$out/package.json"

echo "Bundle ready in $out ($(du -sh "$out" | cut -f1))"
